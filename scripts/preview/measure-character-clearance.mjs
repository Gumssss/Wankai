import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {Vector3,Box3} from 'three';
import {loadGeometry} from './model-geometry.mjs';
import {WEAPON_VISUALS} from '../../src/weapon-visuals.js';
import {WEAPONS} from '../../src/physics.js';

const root=new URL('../../',import.meta.url),bodyFile=new URL('public/models/beagle-smooth-appearance-v05.glb',root);
const body=await loadGeometry(bodyFile),floor=.59,margin=.035;
body.updateMatrixWorld(true);
let envelope=0;
body.traverse(o=>{if(o.isMesh)for(let i=0;i<o.geometry.attributes.position.count;i++){
  const p=o.getVertexPosition(i,new Vector3()).applyMatrix4(o.matrixWorld);p.y-=floor;envelope=Math.max(envelope,p.length());
}});
const bounds=new Box3().setFromObject(body),offsets={},measurements={};
for(const id of ['sword','polearm','hammer']){
  const item=await loadGeometry(new URL(`public/models/${id}.glb`,root));
  item.quaternion.setFromUnitVectors(new Vector3(...WEAPON_VISUALS[id].axis).normalize(),new Vector3(0,1,0));item.updateMatrixWorld(true);
  const scale=WEAPONS[id].length/new Box3().setFromObject(item).getSize(new Vector3()).y;
  const butt=new Vector3(...WEAPON_VISUALS[id].butt).applyQuaternion(item.quaternion).multiplyScalar(scale);
  item.scale.setScalar(scale);item.position.copy(butt).multiplyScalar(-1);item.updateMatrixWorld(true);
  let minY=Infinity;
  item.traverse(o=>{if(o.isMesh)for(let i=0;i<o.geometry.attributes.position.count;i++)minY=Math.min(minY,o.getVertexPosition(i,new Vector3()).applyMatrix4(o.matrixWorld).y);});
  const collisionFloor=Math.min(...WEAPONS[id].colliders.flatMap(c=>[c.a[1]-c.radius,c.b[1]-c.radius]));
  // A separating plane beyond a sphere enclosing every character vertex proves
  // clearance at EVERY pitch/yaw, including triangle interiors and capsules.
  const required=envelope+margin-Math.min(minY,collisionFloor);
  offsets[id]=Math.ceil(Math.max(WEAPONS[id].offset,required)*1000)/1000;
  measurements[id]={originalOffset:WEAPONS[id].offset,minimumVisualY:minY,minimumCapsuleY:collisionFloor,
    resolvedOffset:offsets[id],guaranteedClearance:offsets[id]+Math.min(minY,collisionFloor)-envelope};
}
const report={status:'measured',method:'Conservative enclosing sphere and separating plane, valid for the complete continuous swing/yaw sweep; no mesh edits.',
  source:'public/models/beagle-smooth-appearance-v05.glb',sha256:createHash('sha256').update(await readFile(bodyFile)).digest('hex'),
  bodyFloor:floor,bodyBounds:{min:bounds.min.toArray(),max:bounds.max.toArray()},bodyEnvelopeRadius:envelope,requiredClearance:margin,measurements};
const out=new URL('assets/concepts/beagle/common-weapon-clearance-v01.json',root);
await mkdir(new URL('.',out),{recursive:true});await writeFile(out,JSON.stringify(report,null,2)+'\n');
await writeFile(new URL('src/character-attachments.js',root),`// Generated by scripts/preview/measure-character-clearance.mjs from the actual GLBs.\nexport const BEAGLE_COMMON_OFFSETS=Object.freeze(${JSON.stringify(offsets,null,2)});\nexport const BEAGLE_COMPACT_BOUNDS=Object.freeze(${JSON.stringify(report.bodyBounds)});\n`);
console.log(JSON.stringify(report,null,2));
